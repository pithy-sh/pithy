import type { CliDescription } from "./cliSchema";

/**
 * **The command tree, as the one builder of `pithy` command lines reads it (#711).**
 *
 * Every command a message, an action, a skip reason, a note or a `fix` names is built by
 * `@pithy-sh/core/src/cli/command.ts`, and that builder refuses a command that does not exist, a flag it does
 * not declare, a required flag left off. It can only do that knowing the tree, and it cannot compose the tree
 * itself: it runs in Workers and in every capability package, and the tree is the CLI's. So the tree is
 * projected here, from the same `describeCli` walk `pithy schema` publishes, into a TypeScript module in core —
 * typed `as const`, so a command or a flag that does not exist is a compile error at the line that names it.
 *
 * `commandCatalog.test.ts` fails while the committed file is stale, and `writeCommandCatalog.ts` writes it.
 */

/** Where the generated module lives, relative to the repository root. */
export const COMMAND_CATALOG_PATH = "packages/core/src/cli/commandCatalog.generated.ts";

/** `Omit` over each member of a union, so a discriminated union keeps its discriminant. */
type DistributiveOmit<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never;

/** One positional, as the builder needs it. */
interface CatalogPositional {
  name: string;
  required: boolean;
  variadic: boolean;
}

/** One flag, as the builder needs it. */
interface CatalogFlag {
  type: "boolean" | "string";
  required: boolean;
  repeatable: boolean;
  default?: string;
  enum?: string[];
}

/** One command, as the builder needs it. */
interface CatalogEntry {
  positionals: CatalogPositional[];
  flags: Record<string, CatalogFlag>;
  groups: DistributiveOmit<CliDescription["commands"][number]["flagGroups"][number], "rule">[];
}

/**
 * Every command that runs, by path, projected to what a builder checks: its positionals, its flags with their
 * type, whether they are required, repeat, default or take a fixed set, and the rules over several flags. A
 * group, which only prints its subcommands, is not a command a line can name.
 */
export function commandCatalogOf(cli: Pick<CliDescription, "commands" | "globalFlags">): {
  commands: Record<string, CatalogEntry>;
  globalFlags: string[];
  groups: string[];
} {
  const commands: Record<string, CatalogEntry> = {};
  for (const command of cli.commands) {
    if (!command.runs) continue;
    const flags: Record<string, CatalogFlag> = {};
    for (const flag of command.flags) {
      flags[flag.name] = {
        type: flag.type,
        required: flag.required,
        repeatable: flag.repeatable,
        ...(typeof flag.default === "string" ? { default: flag.default } : {}),
        ...(flag.enum === undefined ? {} : { enum: [...flag.enum] }),
      };
    }
    commands[command.path] = {
      positionals: command.positionals.map((one) => ({
        name: one.name,
        required: one.required,
        variadic: one.variadic,
      })),
      flags,
      // The rule's sentence is the parser's to say; the builder says its own.
      groups: command.flagGroups.map(({ rule: _rule, ...group }) => group),
    };
  }
  return {
    commands,
    globalFlags: cli.globalFlags.flatMap((flag) => [flag.name, ...flag.aliases]).sort(),
    groups: cli.commands.filter((command) => !command.runs).map((command) => command.path),
  };
}

/** The exact bytes the generated module holds. JSON is a TypeScript expression, so the data is written as JSON. */
export function renderCommandCatalog(catalog: ReturnType<typeof commandCatalogOf>): string {
  return [
    "// SPDX-FileCopyrightText: 2026 Pithy",
    "// SPDX-License-Identifier: MIT",
    "",
    "// GENERATED by packages/cli/src/contract/writeCommandCatalog.ts — do not edit by hand. Regenerate with",
    "// `bun run command-catalog`. Every command the CLI runs, as `src/cli/command.ts` builds a line naming one.",
    "",
    "/** Every command the CLI runs, by path: its positionals, its flags and the rules over several flags. */",
    `export const COMMANDS = ${JSON.stringify(catalog.commands, null, 2)} as const;`,
    "",
    "/** The flags every command takes, answered before any command runs. */",
    `export const GLOBAL_FLAGS = ${JSON.stringify(catalog.globalFlags, null, 2)} as const;`,
    "",
    "/** The groups, which only list their subcommands: a sentence may name one, and nobody runs one. */",
    `export const GROUPS = ${JSON.stringify(catalog.groups, null, 2)} as const;`,
    "",
  ].join("\n");
}

import { mkdir, rm } from "node:fs/promises";
import { basename, dirname, join, relative } from "node:path";
import { type AsyncApiDocument, asyncApiDocument, socketGroupsOf } from "@pithy-sh/core/src/asyncapi/document";
import { commandName } from "@pithy-sh/core/src/cli/command";
import { createBackend } from "@pithy-sh/core/src/createBackend";
import { InternalError } from "@pithy-sh/core/src/error/pithyError";
import {
  type OpenApiDocument,
  openApiDocument,
  type UndescribedRoute,
  undescribedRoutes,
} from "@pithy-sh/core/src/openapi/document";
import { routeGroupsOf } from "@pithy-sh/core/src/openapi/routeGroups";
import { z } from "zod";
import { writeFileAtomic } from "../project/atomic";
import { composeForSync, resolveWorkersFor } from "../project/composeFor";
import { allCapabilities, type WorkerConfig } from "../project/config";
import { readOptionalFile } from "../project/readOptionalFile";

/**
 * **`pithy contract` — each Worker's OpenAPI document, read off the app it composes.**
 *
 * `pithy schema` describes the CLI and reads nothing from the project, and that stays true. This reads
 * the project: it loads each Worker's `pithy.config.ts` for one environment, assembles the app the way
 * the Worker does at startup, and hands the route table to core's `openApiDocument`. Every kit route
 * arrives described. The adopter's own routes arrive as far as they are described: a route with a
 * `describeRoute` is written in full, and one without is still written from its `validate` schemas and
 * marked `x-pithy-undescribed`, so a client generated from the document reaches it and the mark says
 * which ones to finish.
 *
 * One environment per document, because the route table is one per environment: `@pithy-sh/auth`
 * mounts its dev sign-in in `dev` and nowhere else. `prod` is the default — it is the table a shipped
 * client calls.
 */

/** The file each Worker's HTTP document is written to. */
export const CONTRACT_FILE = "openapi.json";

/** The sentence every document this command writes carries, and the one it recognizes its own files by. */
const GENERATED_BY = `Generated by \`${commandName("contract")}\`.`;

/** The file each Worker's socket document is written to, beside it — only for a Worker that serves a socket. */
export const SOCKET_CONTRACT_FILE = "asyncapi.json";

/** One Worker's contract, as `pithy contract --json` reports it. */
export const WorkerContractReport = z
  .object({
    worker: z.string().describe("The Worker's `apps/` directory."),
    path: z.string().describe("Where its document was written, relative to the project root."),
    operations: z.number().int().describe("How many operations the document holds, one per method and path."),
    undescribed: z
      .array(
        z
          .object({
            method: z.string().describe("The HTTP method, as Hono records it."),
            path: z.string().describe("The route's path pattern."),
          })
          .describe("A route with no `describeRoute`."),
      )
      .describe(
        "Routes written from their validators alone and marked `x-pithy-undescribed`. Empty when every route is described.",
      ),
    changed: z.boolean().describe("Whether the file's contents changed. False when it already matched."),
    asyncapi: z
      .object({
        path: z.string().describe("Where its AsyncAPI document was written, relative to the project root."),
        channels: z.number().int().describe("How many sockets the document describes."),
        changed: z.boolean().describe("Whether the file's contents changed. False when it already matched."),
      })
      .nullable()
      .describe("Its AsyncAPI document, for the sockets it serves, or `null` for a Worker that serves none."),
  })
  .describe("One Worker's OpenAPI document, and its AsyncAPI document when it serves a socket.");
export type WorkerContractReport = z.infer<typeof WorkerContractReport>;

/** Everything one Worker's document is built from. */
export interface WorkerContractInput {
  /** The Worker's `apps/` directory name. Becomes the document's title, beside the project's. */
  worker: string;
  /** The project's name, from the root `pithy.config.ts`. */
  project: string;
  /** The version the document states. The project's own `package.json` version, or `0.0.0`. */
  version: string;
  /** The loaded Worker config. Must already be evaluated for the environment being documented. */
  config: WorkerConfig;
}

/** Assemble one Worker's app and read its document off it. Run inside a composition for the environment. */
export function workerDocument(input: WorkerContractInput): {
  document: OpenApiDocument;
  undescribed: UndescribedRoute[];
  sockets: AsyncApiDocument | null;
} {
  const app = createBackend({
    capabilities: input.config.capabilities,
    ...(input.config.app ? { app: input.config.app } : {}),
  });
  const groups = routeGroupsOf(app);
  if (groups === undefined) {
    throw new InternalError({ detail: "createBackend assembled an app without recording its route groups." });
  }
  const document = openApiDocument(
    {
      title: `${input.project} ${input.worker}`,
      version: input.version,
      description: `The HTTP contract of the ${input.worker} Worker. ${GENERATED_BY} Do not edit by hand.`,
    },
    groups,
    { undescribed: "include" },
  );
  // Read after assembly, so a socket a capability declares from its composed config is the one it mounted.
  const socketGroups = socketGroupsOf(allCapabilities(input.config));
  const sockets =
    socketGroups.length === 0
      ? null
      : asyncApiDocument(
          {
            title: `${input.project} ${input.worker}`,
            version: input.version,
            description: `The socket contract of the ${input.worker} Worker. ${GENERATED_BY} Do not edit by hand.`,
          },
          socketGroups,
        );
  return { document, undescribed: undescribedRoutes(groups), sockets };
}

/** A document as it is written to disk: two-space JSON and a trailing newline, so a rewrite is a clean diff. */
export function renderDocument(document: OpenApiDocument | AsyncApiDocument): string {
  return `${JSON.stringify(document, null, 2)}\n`;
}

/** How many operations a document holds. */
export function operationCount(document: OpenApiDocument): number {
  return Object.values(document.paths).reduce((count, item) => count + Object.keys(item).length, 0);
}

/** The version a project's documents state: its root `package.json` version, or `0.0.0` when it has none. */
export async function projectVersion(projectDir: string): Promise<string> {
  const source = await readOptionalFile(join(projectDir, "package.json"));
  if (source === null) return "0.0.0";
  const parsed = z
    .object({ version: z.string().describe("The project's version.") })
    .describe("The one field read from a package.json.")
    .safeParse(JSON.parse(source));
  return parsed.success ? parsed.data.version : "0.0.0";
}

/** What {@link writeContracts} needs. */
export interface WriteContractsOptions {
  projectDir: string;
  /** The project's name, for each document's title. */
  project: string;
  /** The environment the Workers are composed for. Already validated. */
  environment: string;
  /** Only this Worker, by `apps/` name. Every Worker when absent. */
  worker?: string;
  /** Write every document here as `<dir>/<worker>/openapi.json`. Each Worker's own directory when absent. */
  outDir?: string;
}

/**
 * Write a document only when its bytes differ, so a second run is a no-op. `--out` names a directory that may
 * not exist yet; a Worker's own directory always does.
 */
async function writeIfChanged(
  path: string,
  rendered: string,
  mayCreate: boolean,
): Promise<{ path: string; changed: boolean }> {
  const changed = (await readOptionalFile(path)) !== rendered;
  if (changed) {
    if (mayCreate) await mkdir(dirname(path), { recursive: true });
    await writeFileAtomic(path, rendered);
  }
  return { path, changed };
}

/**
 * A Worker that stopped serving sockets keeps no socket contract: a stale `asyncapi.json` beside a current
 * `openapi.json` describes a socket that is gone, and a client generated from it builds for nothing. Removed
 * only when it is one this command wrote — an AsyncAPI document whose description says so — so a file the
 * adopter keeps there by hand is left alone. Always `null`: there is no socket document to report.
 */
async function removeStaleSocketContract(path: string): Promise<null> {
  const source = await readOptionalFile(path);
  if (source === null) return null;
  let generated = false;
  try {
    const parsed = JSON.parse(source) as { asyncapi?: unknown; info?: { description?: unknown } };
    generated =
      typeof parsed.asyncapi === "string" &&
      typeof parsed.info?.description === "string" &&
      parsed.info.description.includes(GENERATED_BY);
  } catch {
    generated = false;
  }
  if (generated) await rm(path, { force: true });
  return null;
}

/** Compose each selected Worker for the environment, and write its documents where they belong. */
export async function writeContracts(options: WriteContractsOptions): Promise<WorkerContractReport[]> {
  const version = await projectVersion(options.projectDir);
  // Loaded for the environment, then assembled for it: a capability reads the environment both when its
  // config is evaluated and when its routes register (`@pithy-sh/auth`'s dev sign-in is the second kind).
  const workers = await resolveWorkersFor(options.environment, {
    projectDir: options.projectDir,
    ...(options.worker === undefined ? {} : { worker: options.worker }),
  });
  const reports: WorkerContractReport[] = [];
  for (const worker of workers) {
    // The `apps/` directory, never the wrangler name: it is what `--worker` takes and what `--out` nests by.
    const name = basename(worker.dir);
    const { document, undescribed, sockets } = composeForSync(options.environment, () =>
      workerDocument({ worker: name, project: options.project, version, config: worker.config }),
    );
    const dir = options.outDir === undefined ? worker.dir : join(options.outDir, name);
    const written = await writeIfChanged(
      join(dir, CONTRACT_FILE),
      renderDocument(document),
      options.outDir !== undefined,
    );
    const socketsPath = join(dir, SOCKET_CONTRACT_FILE);
    const socketsWritten =
      sockets === null
        ? await removeStaleSocketContract(socketsPath)
        : await writeIfChanged(socketsPath, renderDocument(sockets), options.outDir !== undefined);
    reports.push({
      worker: name,
      path: relative(options.projectDir, written.path),
      operations: operationCount(document),
      undescribed: undescribed.map(({ method, path }) => ({ method, path })),
      changed: written.changed,
      asyncapi:
        sockets === null || socketsWritten === null
          ? null
          : {
              path: relative(options.projectDir, socketsWritten.path),
              channels: Object.keys(sockets.channels).length,
              changed: socketsWritten.changed,
            },
    });
  }
  return reports;
}

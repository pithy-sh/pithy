import type { CapabilityManifest } from "@pithy-sh/core/src/capability/manifest";
import { KIT_ADD_FACTS } from "./kitAddFacts.generated";

/**
 * **What a `pithy add` line needs to know about a capability that is not installed yet (#711).**
 *
 * `addCommand.ts` names `--with-prerequisites` from a manifest's peers, and the `--set` a required option needs
 * from its options. Both live in the package's `pithy.manifest.json`, and the line is most often written exactly
 * when the package is absent: `pithy doctor`'s entitlement line names `pithy add payments` in a project that has
 * never installed it. Read as "no manifest, so nothing required", that line named a command refused for
 * `billingSubject`. So the kit's own manifests are projected here, and an installed manifest is read first,
 * because the project's copy is the one `pithy add` will run against.
 */

/** The half of a manifest a `pithy add` line reads: the peers it brings, and the options it cannot default. */
export interface AddFacts {
  /** The capability, as `pithy add` takes it. */
  readonly name: string;
  /** The capabilities it declares as prerequisites. */
  readonly peerCapabilities: readonly string[];
  /** Every option it states no default for, in manifest order. */
  readonly requiredOptions: readonly RequiredAddOption[];
}

/** An option with no default: the key `--set` answers, and the values it takes. */
export interface RequiredAddOption {
  /** The option's key, as `--set key=value` spells it. */
  readonly key: string;
  /** The closed set of values it takes, when it states one. */
  readonly choices?: readonly string[] | undefined;
  /** Choices `pithy add` refuses, which a line therefore never offers. */
  readonly choicesNeedingCode?: Readonly<Record<string, string>> | undefined;
}

/** A manifest projected to {@link AddFacts}. */
export function addFactsOf(manifest: CapabilityManifest): AddFacts {
  return {
    name: manifest.name,
    peerCapabilities: [...manifest.peerCapabilities],
    requiredOptions: manifest.configOptions
      .filter((option) => option.default === undefined)
      .map((option) => ({
        key: option.key,
        ...(option.choices === undefined ? {} : { choices: [...option.choices] }),
        ...(option.choicesNeedingCode === undefined ? {} : { choicesNeedingCode: { ...option.choicesNeedingCode } }),
      })),
  };
}

/** Where the generated table lives, relative to the repository root. */
export const KIT_ADD_FACTS_PATH = "packages/cli/src/capabilities/kitAddFacts.generated.ts";

/** The exact bytes the generated table holds, from every kit manifest. */
export function renderKitAddFacts(manifests: readonly CapabilityManifest[]): string {
  const facts = Object.fromEntries(
    [...manifests]
      .sort((left, right) => left.name.localeCompare(right.name))
      .map((manifest) => {
        const { name, ...rest } = addFactsOf(manifest);
        return [name, rest];
      }),
  );
  return [
    "// SPDX-FileCopyrightText: 2026 Pithy",
    "// SPDX-License-Identifier: MIT",
    "",
    "// GENERATED by packages/cli/src/contract/writeCommandCatalog.ts — do not edit by hand. Regenerate with",
    "// `bun run command-catalog`. Each kit capability's peers and the options it cannot default (kitAddFacts.ts).",
    "",
    "/** Each kit capability's prerequisites and required options, by name. */",
    `export const KIT_ADD_FACTS = ${JSON.stringify(facts, null, 2)} as const;`,
    "",
  ].join("\n");
}

/** The kit's own facts for one capability, when the kit has one by that name. */
export function kitAddFacts(name: string): AddFacts | undefined {
  if (!Object.hasOwn(KIT_ADD_FACTS, name)) return undefined;
  const facts = KIT_ADD_FACTS[name as keyof typeof KIT_ADD_FACTS] as Omit<AddFacts, "name">;
  return { name, ...facts };
}

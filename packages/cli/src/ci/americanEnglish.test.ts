/** Every word the census refuses: the irregulars, plus each `-ise` stem crossed with each ending. */
const WORDS: readonly BritishWord[] = [
  ...IRREGULAR,
  ...ISE_STEMS.flatMap((stem) =>
    ISE_ENDINGS.map((ending) => ({ gb: `${stem}${ending}`, us: `${stem}${ending.replace("is", "iz")}` })),
  ),
];

/** The word, whatever its case, with a boundary at each end. Whole words only — see {@link BritishWord.near}. */
const PATTERN = new RegExp(`\\b(${WORDS.map((word) => word.gb).join("|")})\\b`, "gi");

/** en-GB spelling → the entry that refuses it. */
const BY_WORD = new Map(WORDS.map((word) => [word.gb, word]));

/** The marker that says a line quotes somebody else. It exempts that line and the one after it, and no more. */
const QUOTED = /en-GB verbatim:\s*\S/;

/** What every generator in this repository writes into the head of what it produces. */
const GENERATED = /\bGENERATED by\b/;

/** How far into a file the generator's marker has to be, so a file mentioning it in prose is still read. */
const HEAD_LINES = 25;

/** One en-GB spelling, where it is. */
interface Finding {
  /** The file, relative to the repository root, in POSIX separators. */
  readonly path: string;
  /** 1-indexed line. */
  readonly line: number;
  /** 1-indexed column. */
  readonly column: number;
  /** The word as it is written, case and all. */
  readonly word: string;
  /** What to write instead, in the same case. */
  readonly american: string;
  /** Why this one wants reading rather than replacing, when it does. */
  readonly read?: string;
}

/** `american`, capitalized when `written` was. */
function matchCase(written: string, american: string): string {
  return written[0] === written[0]?.toUpperCase() ? `${american[0]?.toUpperCase()}${american.slice(1)}` : american;
}

/**
 * Every span on one line whose quoted content holds no whitespace — a token, not a sentence.
 *
 * Left to right, in whichever of the three quote characters opened it, and **a span that turns out to hold a
 * sentence is not skipped over**: that is what lets a backticked token inside a prose string literal still count,
 * which is how this repository names a wire value in a `.describe()`.
 */
function valueSpans(line: string): [number, number][] {
  const spans: [number, number][] = [];
  for (let index = 0; index < line.length; index += 1) {
    const quote = line[index];
    if (quote !== '"' && quote !== "'" && quote !== "`") continue;
    const close = line.indexOf(quote, index + 1);
    if (close === -1) continue;
    const inner = line.slice(index + 1, close);
    if (inner.length === 0 || /\s/.test(inner)) continue;
    spans.push([index + 1, close]);
    index = close;
  }
  return spans;
}

/** Every en-GB spelling in `text` that is this project's own prose. */
function census(path: string, text: string): Finding[] {
  const lines = text.split("\n");
  if (lines.slice(0, HEAD_LINES).some((line) => GENERATED.test(line))) return [];
  const found: Finding[] = [];
  for (const [index, line] of lines.entries()) {
    if (QUOTED.test(line) || (index > 0 && QUOTED.test(lines[index - 1] as string))) continue;
    const spans = valueSpans(line);
    for (const match of line.matchAll(PATTERN)) {
      const at = match.index;
      if (spans.some(([open, close]) => at >= open && at + match[0].length <= close)) continue;
      const word = BY_WORD.get(match[0].toLowerCase()) as BritishWord;
      found.push({
        path,
        line: index + 1,
        column: at + 1,
        word: match[0],
        american: matchCase(match[0], word.us),
        ...(word.read === undefined ? {} : { read: word.read }),
      });
    }
  }
  return found;
}

/** A path relative to the repository root, in POSIX form. */
function fromRoot(path: string): string {
  return relative(REPO_ROOT, path).split(sep).join("/");
}

/** Does this file hold prose? */
function isProse(name: string): boolean {
  return PROSE.some((extension) => name.endsWith(extension));
}

/**
 * Is this a package's own prose — `src/`, `docs/`, or the `README.md` at its root?
 *
 * All three ship. Sixteen of the eighteen manifests declare no `files`, so a package's `README.md` and its
 * `docs/` land in the tarball an adopter installs, and `@pithy-sh/payments` names `docs` explicitly. A README
 * is the most-read prose this project writes; leaving it out would have made the census truest about the
 * files fewest adopters open.
 *
 * Narrowed by the segment rather than by "holds `/src/` somewhere", which was the first spelling and was
 * wrong in a way that only showed up in a finding: `packages/ui-react/templates/src/routes/pithy/sign-in.tsx`
 * is a seeded adopter file under a package's `templates/`, and it matched.
 */
function isPackageProse(path: string): boolean {
  const segments = relative(join(REPO_ROOT, "packages"), path).split(sep);
  if (segments[1] === "src" || segments[1] === "docs") return true;
  return segments.length === 2 && segments[1] === "README.md";
}

/**
 * Every file the census reads. `packages` is narrowed to each package's own prose.
 *
 * Narrowed by the segment rather than by "holds `/src/` somewhere", which was the first spelling and was
 * wrong in a way that only showed up in a finding: `packages/ui-react/templates/src/routes/pithy/sign-in.tsx`
 * is a seeded adopter file under a package's `templates/`, and it matched. Whichever way that scope goes it
 * has to be the one the header claims.
 */
function corpus(): string[] {
  const found: string[] = [];
  for (const root of ROOTS) {
    for (const path of sourcePaths(join(REPO_ROOT, root), { keep: isProse })) {
      if (root === "packages" && !isPackageProse(path)) continue;
      found.push(path);
    }
  }
  return found;
}

/** One finding, as the reader sees it. */
function describeFinding(finding: Finding): string {
  const read = finding.read === undefined ? "" : `  — read it: ${finding.read}`;
  return `${finding.path}:${finding.line}:${finding.column}  ${finding.word} → ${finding.american}${read}`;
}

/** How many findings the failure lists before it stops. The headline always carries the true total. */
const LISTED = 50;

describe("the words this project writes are American", () => {
  test("no en-GB spelling in this repository's own prose", () => {
    const files = corpus();
    const findings = files.flatMap((path) => {
      const text = readSource(path);
      return text === null ? [] : census(fromRoot(path), text);
    });
    const report = findings.map(describeFinding);
    const headline = [
      `${findings.length} en-GB spellings in ${new Set(findings.map((finding) => finding.path)).size} of ${files.length} files.`,
      "Each line is file:line:column and the word to write instead.",
      "A wire value, an enum arm or a field name is exempt by being a lone token in quotes or backticks.",
      'A quotation from an API we do not own is exempt by "en-GB verbatim: <reason>" on its line or the line above.',
      report.length > LISTED ? `Listing the first ${LISTED} of ${report.length}.` : "",
    ]
      .filter(Boolean)
      .join("\n");
    expect(report.slice(0, LISTED), headline).toEqual([]);
  });

  test("the census reads the tree it says it reads", () => {
    // Shape 8 in `./sweepPopulation.test.ts`: a guard far below the real population passes over nothing. Every
    // root contributes, and the whole is near the 2,000 files measured on 2026-08-22 — a walk that broke and
    // returned three files would otherwise report a clean tree.
    const files = corpus().map(fromRoot);
    expect(files.length).toBeGreaterThanOrEqual(1900);
    for (const root of ROOTS) {
      expect(
        files.filter((path) => path.startsWith(`${root}/`)).length,
        `${root} contributes nothing to the census`,
      ).toBeGreaterThan(0);
    }
    expect(
      files.some((path) => path.endsWith(".md")),
      "no guide is read",
    ).toBe(true);
    expect(
      files.some((path) => path.endsWith(".ts")),
      "no TypeScript is read",
    ).toBe(true);
    // Narrowed to each package's own prose — `src/`, `docs/` and the root `README.md` — which is the scope
    // the header claims rather than an accident of the walk. `packages/ui-react/templates/src/` is the one
    // that reads as source and is not, and a package's `templates/` is somebody else's file waiting to be
    // copied rather than something we wrote.
    const PACKAGE_PROSE = /^packages\/[^/]+\/(src|docs)\/|^packages\/[^/]+\/README\.md$/;
    expect(files.filter((path) => path.startsWith("packages/") && !PACKAGE_PROSE.test(path))).toEqual([]);
  });
});


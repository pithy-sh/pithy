/**
 * **The words this project writes are American.**
 *
 * Not a style preference — a census, over every file this repository writes prose into. `pithy-sh/dashboard#82`
 * standardized one word and stopped there, and #434 counted what the stopping left: hundreds of en-GB spellings
 * across doc comments, `.describe()` text, guides and manifests, in a kit that is otherwise American. A tree that
 * is mostly one way makes the other way harder to see, not easier, which is why this is a gate rather than a
 * sweep somebody repeats by hand every quarter.
 *
 * ## The rule, and the three things it is not about
 *
 * The rule is about **prose** — the sentences we write. Three kinds of en-GB spelling in this tree are not our
 * prose at all, and a census that flagged them would be asking for a rename of somebody else's data:
 *
 * 1. **A wire value.** `packages/email/src/data/enums.ts` stores an email job's state as `cancelled` and
 *    `packages/cloudflare/src/workers/workersBuildEvent.ts` reads the same spelling back from Cloudflare's
 *    build events. Those strings are in D1 rows and on the wire. Rewriting one is a migration and a breaking
 *    change, not a word swap — #434 says so at length — and it is a decision taken with a changeset, never by
 *    a gate.
 * 2. **A generated vendor notice.** A file a generator wrote carries the generator's wording, or somebody
 *    else's. It is fixed by fixing the generator, and editing it by hand is undone on the next run.
 * 3. **A quoted third-party string.** An error message or a field name from an API we do not own is quoted, not
 *    written. Correcting the quotation makes it stop matching what the API sends.
 *
 * ## How each exemption is decided, and why none of them is a list of paths
 *
 * **A hand-maintained allow-list of files is the defect `./turboInputs.test.ts` refuses one level up**, and #432
 * spent three days on why: a list is right on the day it is written and silently wrong afterwards, and the way
 * it goes wrong is that the gate keeps passing. So all three exemptions here are derived from the site.
 *
 * - **A lone token in code formatting is data.** A quoted or backticked run with no whitespace in it —
 *   `"cancelled"`, `` `subscription_cancelled` ``, `'colour'` — is a value, a key, an enum arm or an identifier
 *   being named. A sentence in quotes is prose and is still read, whitespace and all, which is why the
 *   `.describe()` beside an enum arm is reported while the arm is not. That single structural fact — **token,
 *   not sentence** — separates the email job's stored state from the sentence describing it, in the same file,
 *   with neither of them named anywhere. It is how this repository already writes about a wire value in prose,
 *   so nothing had to be restyled to earn it, and it is why this file can state its own word list without
 *   failing itself: a word named as a word is a token.
 * - **A generated file is the generator's output.** This repository has one convention for saying so, on the
 *   fourth line of every `version.generated.ts` and of `email/src/templates/precompiled.generated.ts`:
 *   `GENERATED by <script> — do not edit by hand.` The census reads that marker in a file's head and skips the
 *   file. The generator itself is source like any other; where it lives inside {@link ROOTS} the census reads it.
 * - **A quotation is marked where it is made.** One marker, `en-GB verbatim:`, in a comment on the offending
 *   line or the line above it, with the reason after the colon. It exempts **that line and no other** — never a
 *   file, never a directory — so it cannot grow into the list it replaces, and `git grep "en-GB verbatim:"` is the
 *   whole set of them. A marker with nothing after the colon exempts nothing: a shrug is not a reason.
 *
 * What this cannot do is check that a marker's reason is *true*, which is the same wall
 * `packages/ui-react/src/seededGates.test.ts` records for its own ledger. What it can do is make the claim
 * explicit, local, and greppable at the moment somebody makes it.
 *
 * ## Watched failing before it was trusted
 *
 * Run against the tree it was written for, with #434's sweep still ahead of it:
 *
 *     AssertionError: 938 en-GB spellings in 457 of 2025 files.
 *     - packages/audit/src/http/guards.ts:73:71  `customised` → customized
 *     - packages/audit/src/http/routeContract.test.ts:165:45  `greys` → grays
 *     - packages/auth/src/admin/users.ts:223:4  `optimisation` → optimization
 *     … and 935 more
 *
 * The very first run, over the untouched tree, found 973 in 464 files — and eight of them were in this
 * file's own header. It reads itself, like every file under {@link ROOTS}, which is the only way a census
 * can be believed about anybody else. Sixty-three of the findings were identifiers rather than sentences,
 * and the gate named them rather than deciding for the package that owns them. That package decided:
 * `offense()` in `./fileModes.ts`, and `analyze()` alongside `analyzeDrivers()` in `./workflowDrivers.ts`
 * and both of its importers. An identifier is either prose-shaped or it is a value something else
 * depends on, and only the package holding it knows which.
 *
 * Each finding names a file, a line, a column and the word, because a gate whose failure a reader cannot act on
 * is half a gate. The three exemptions were proven the same way and in the same tree: a wire value, a generated
 * notice and a quoted third-party message were each planted, the census stayed green over all three, and each
 * was removed again.
 *
 * ## What is outside its reach, said out loud
 *
 * {@link ROOTS} is #434's scope: each package's `src/`, `docs/` and `README.md`, plus `templates`, `docs`
 * and `tooling`. `packages/*​/templates`,
 * `apps/`, `scripts/`, `.changeset/` and the repository's root guides are prose this project writes too, and
 * they are not read here — roughly two hundred further occurrences sit in them. That is a boundary, not a
 * judgment, and it is written down rather than left for the next reader to discover from a green run: widening
 * {@link ROOTS} is one edit, and it should follow the sweep that empties them.
 *
 * `.svg` artwork and `tooling/license-headers/licenses/*.txt` are excluded by {@link PROSE}. The license texts
 * are the clearest case in the tree of somebody else's words: quoted in full, byte-for-byte, with no comment
 * syntax to carry a marker. A verbatim document is not prose we write.
 */

